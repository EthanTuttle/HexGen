#!/usr/bin/env python3
"""Generates scripts/creator/creator_data.gd from the Character creator v22b mockup, so its names, blurbs, card text and
icons copy straight across. The mockup's tables are JavaScript, so macOS's own JavaScript runs them.
Run from the repo root: python3 godot/tools/creator_data.py"""
import json, re, subprocess

SRC = "mockups/character-creator/Creator-v22b-Banners.dc.html"
OUT = "godot/scripts/creator/creator_data.gd"
NAMES = ["AB", "IC", "TER", "CLS", "HEART", "CX", "GX", "W", "SKIN", "HAIR", "EYES", "CLOTH", "RACES", "BGS", "HAIRD", "HORN",
    "DARK", "RCOL", "RIC", "FLAME", "RX", "SX", "PI", "DRI", "RSP", "BSP", "RP", "SP2", "SUBI", "ELEM", "BBL", "PROFB", "PROFI",
    "LOC", "PROFD", "WC", "WM", "WG", "HL", "HN"]
OMIT = {"HEART", "FLAME", "W"}   # the weapons list is Gear.WEAPONS (scripts/game/gear.gd)
GEAR_KEYS = {"CLS": ["w", "a", "sh"], "CX": ["at"]}   # each class's gear and armour line come from Gear.CLASS_GEAR
text = open(SRC).read()
start = text.index('data-dc-script')
js = text[text.index("\n", start):text.index("</script>", start)]

def statement(name):
    m = re.search(r"const %s=" % name, js)
    if not m:
        raise SystemExit("not found: " + name)
    i = m.end()
    depth = 0
    quote = None
    while True:
        c = js[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif c in "'\"`":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ";" and depth == 0:
            return "var %s=%s;" % (name, js[m.end():i])
        i += 1

extra = "\n".join(l for l in js.split("\n") if l.startswith("IC['w_"))
body = "\n".join(statement(n) for n in NAMES[:NAMES.index("W") + 1])
wline = re.search(r"const W=.*?\n(.*?)\nIC\['w_", js, re.S)
script = body + "\n" + (wline.group(1) if wline else "") + "\n" + extra + "\n" + "\n".join(statement(n) for n in NAMES[NAMES.index("W") + 1:])
script += "\nJSON.stringify({%s});" % ",".join(n + ":" + n for n in NAMES if n not in OMIT)
out = subprocess.run(["osascript", "-l", "JavaScript", "-e", script], capture_output=True, text=True)
if out.returncode:
    raise SystemExit(out.stderr[:800])
data = json.loads(out.stdout)
for table, keys in GEAR_KEYS.items():
    for row in (data[table] if isinstance(data[table], list) else data[table].values()):
        for k in keys:
            row.pop(k, None)
lines = ["class_name CreatorData", "extends RefCounted", "## GENERATED by tools/creator_data.py from Character creator v22b. Don't edit by hand.", ""]
for k, v in data.items():
    lines.append("const %s = %s" % (k, json.dumps(v, ensure_ascii=False)))
open(OUT, "w").write("\n".join(lines) + "\n")
print({k: len(v) for k, v in data.items()})
