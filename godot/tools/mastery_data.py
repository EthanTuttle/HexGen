#!/usr/bin/env python3
"""Generates scripts/game/mastery_data.gd from the weapon mastery tables in design/04 Weapons & gear.md, so every node's
name, kind, AP and text copy straight across for the Weapon mastery screen (07 -> Weapon mastery screen).
Run from the repo root: python3 godot/tools/mastery_data.py"""
import json, re

SRC = "design/04 Weapons & gear.md"
OUT = "godot/scripts/game/mastery_data.gd"
KEYS = {"brass knuckles": "knuckles"}

trees = {}
weapon = None
for line in open(SRC, encoding="utf-8"):
    line = line.rstrip("\n")
    h = re.match(r"### (\w[\w ]*?) \((.*)\)$", line)
    if h:
        name = h.group(1).strip()
        key = KEYS.get(name.lower(), name.lower())
        weapon = {"n": name, "base": h.group(2), "rows": []}
        trees[key] = weapon
        continue
    if weapon is None or not line.startswith("|"):
        if line.startswith("## "):
            weapon = None
        continue
    cells = [c.strip() for c in line.strip("|").split("|")]
    if cells[0] == "Node":
        weapon["rows"] = [{"branch": re.sub(r"\s*\(.*\)$", "", c), "two_handed": "two-handed only" in c, "nodes": []} for c in cells[1:]]
        continue
    if not re.match(r"[123]", cells[0]) or not weapon["rows"]:
        continue
    for row, cell in zip(weapon["rows"], cells[1:]):
        m = re.match(r"New card: (.+?) \((\d) AP\): (.*)$", cell)
        if m:
            node = {"n": m.group(1), "kind": "card", "ap": int(m.group(2)), "text": m.group(3)}
        else:
            m = re.match(r"\*\*(.+?)\*\*( \(passive\))?: (.*)$", cell)
            if not m:
                raise SystemExit("can't read: " + cell)
            node = {"n": m.group(1), "kind": "passive" if m.group(2) else "upgrade", "ap": -1, "text": m.group(3)}
        node["text"] = re.sub(r" \([^)]*see [^)]*\)", "", node["text"][0].upper() + node["text"][1:])   # the doc's cross-references
        if not node["text"].endswith("."):
            node["text"] += "."
        row["nodes"].append(node)

trees = {k: v for k, v in trees.items() if v["rows"]}
# Weapon passives (04 -> Weapon rules), shown beside the category cards on the tree: first sentence only (07 v3 drops
# "Stacks with the Rogue's Sneak Attack").
passives = {}
for line in open(SRC, encoding="utf-8"):
    m = re.match(r"\s+- \*\*(Reach|Long Range|Point Blank|Backstab)\*\* \(([^)]*)\): (.*?\.)", line)
    if m:
        text = re.sub(r" \(see [^)]*\)", "", m.group(3)[0].upper() + m.group(3)[1:])
        for w in m.group(2).split(", "):
            passives.setdefault(w, []).append({"n": m.group(1), "text": text})
lines = ["class_name MasteryData", "extends RefCounted", "## GENERATED by tools/mastery_data.py from design/04 -> Weapon mastery. Don't edit by hand.",
    "## TREES[category] = {n, base (the heading's note), rows: [{branch, two_handed, nodes: [{n, kind (card, upgrade, passive), ap (-1 if none), text}]}]}",
    "## PASSIVES[category] = [{n, text}] (04 -> Weapon rules)", ""]
lines.append("const TREES = " + json.dumps(trees, ensure_ascii=False))
lines.append("const PASSIVES = " + json.dumps(passives, ensure_ascii=False))
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print({k: [len(r["nodes"]) for r in v["rows"]] for k, v in trees.items()})
