"""Writes art/combat/maps/README.md, the list of the combat maps in use, from art/export/combat_maps*.json, so it can't drift.

Run: python3 art/scripts/map_catalogue.py (the map render scripts also call it, and keep_image, whenever a map changes).
In use: every map in the JSON files, its current image at the stable, unversioned path art/combat/maps/<map id>.png.
Retired: every other map with a render in art/preview. history.json beside the README remembers each map's details from the
last time it was in use, so a map keeps its idea, shape and size after it leaves the JSON.
"""
import glob
import json
import os
import re
import shutil
import subprocess

ART = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
MAPS = os.path.join(ART, "combat", "maps")
PREVIEW = os.path.join(ART, "preview")
HISTORY = os.path.join(MAPS, "history.json")
TERRAINS = (("Forest", "combat_maps.json", "forest_map_"), ("Plains", "combat_maps_plains.json", "plains_map_"))


def keep_image(prefix, name):
    """Call straight after rendering a map: copies its newest render to the map's stable path."""
    newest = max(glob.glob(os.path.join(PREVIEW, f"{prefix}{name}_v*.png")), key=os.path.getmtime)
    os.makedirs(MAPS, exist_ok=True)
    shutil.copyfile(newest, os.path.join(MAPS, f"{name}.png"))


def committed(path):
    """When a file was last committed, or now if it hasn't been yet."""
    out = subprocess.run(["git", "log", "-1", "--format=%ct", "--", path], cwd=ART, capture_output=True, text=True).stdout.strip()
    return int(out) if out else 2 ** 40


def last_render(prefix, name):
    """Version numbers aren't all in order, so by commit date, then number."""
    files = glob.glob(os.path.join(PREVIEW, f"{prefix}{name}_v*.png"))
    number = lambda f: int(re.search(r"_v(\d+)[a-z]?\.png$", f).group(1))
    return os.path.relpath(max(files, key=lambda f: (committed(f), number(f))), MAPS)


def cell(text):
    return str(text).replace("|", "/")


def rendered(prefix):
    names = set()
    for f in glob.glob(os.path.join(PREVIEW, f"{prefix}*_v*.png")):
        names.add(re.sub(r"(_turned)?_v\d+[a-z]?\.png$", "", os.path.basename(f))[len(prefix):])
    return names


def write():
    history = json.load(open(HISTORY)) if os.path.exists(HISTORY) else {}
    out = ["# Combat maps in use", "",
           "Generated by `art/scripts/map_catalogue.py` from `art/export/combat_maps*.json`; don't edit by hand. Each in-use map's current image is at `art/combat/maps/<map id>.png`, an unversioned path refreshed whenever the map changes. Use these, not `art/preview`, whose version numbers aren't all in order.", ""]
    retired = []
    for terrain, file, prefix in TERRAINS:
        path = os.path.join(ART, "export", file)
        data = json.load(open(path)) if os.path.exists(path) else {}
        out += [f"## {terrain}", ""]
        for variant in dict.fromkeys(m["variant"] for m in data.values()):
            out += [f"### {variant.replace('_', ' ').capitalize()}", "", "| Map id | Status | Base shape | Cells (walkable) | Tactical idea | Kind | Image |", "| --- | --- | --- | --- | --- | --- | --- |"]
            for name, m in data.items():
                if m["variant"] != variant:
                    continue
                walk = sum(c["kind"] != "blocked" for c in m["cells"])
                details = {"shape": m["shape"], "cells": len(m["cells"]), "walkable": walk, "idea": m["idea"], "kind": m.get("kind", "terrain")}
                history[name] = details
                image = f"[![{name}]({name}.png)]({name}.png)" if os.path.exists(os.path.join(MAPS, f"{name}.png")) else "not rendered"
                out.append(f"| `{name}` | in use | {cell(details['shape'])} | {details['cells']} ({walk}) | {cell(details['idea'])} | {details['kind']} | {image} |")
            out.append("")
        retired += [(name, prefix) for name in sorted(rendered(prefix) - set(data))]
    out += ["## Retired", "", "Not in the game's data. Kept so nothing's lost; the image is the map's last render.", "", "| Map id | Base shape | Cells (walkable) | Tactical idea | Last render |", "| --- | --- | --- | --- | --- |"]
    for name, prefix in retired:
        h = history.get(name, {})
        size = f"{h['cells']} ({h['walkable']})" if "cells" in h else "not recorded"
        render = last_render(prefix, name)
        out.append(f"| `{name}` | {cell(h.get('shape', 'not recorded'))} | {size} | {cell(h.get('idea', 'not recorded'))} | [{os.path.basename(render)}]({render}) |")
    with open(os.path.join(MAPS, "README.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    with open(HISTORY, "w") as fh:
        json.dump(history, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print("CATALOGUE", os.path.join(MAPS, "README.md"))


if __name__ == "__main__":
    write()
